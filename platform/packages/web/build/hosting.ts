/**
 * Writes the static-hosting security headers into the build (Hostinger = Apache/LiteSpeed reads
 * .htaccess). The Content-Security-Policy only allows our own scripts, our API and image hosts.
 * Shared by the customer and vendor apps (vite.config.ts imports it from @rozbazaar/web/hosting).
 */

/** Structurally Vite plugins — typed locally so this kit does not depend on Vite. */
interface HeaderResponse {
  setHeader(name: string, value: string): void;
}
interface PreviewServer {
  middlewares: { use(fn: (req: unknown, res: HeaderResponse, next: () => void) => void): void };
}
export type HostingPlugin =
  | {
      name: string;
      apply: 'build';
      generateBundle(this: {
        emitFile(file: { type: 'asset'; fileName: string; source: string }): string;
      }): void;
    }
  | {
      name: string;
      apply: (config: unknown, env: { isPreview?: boolean }) => boolean;
      configurePreviewServer(server: PreviewServer): void;
    };

/**
 * Returns two plugins: one writes .htaccess into the build, the other makes `vite preview` send the
 * same headers, so the production build can be tested locally under the real CSP.
 */
export function hostingHeaders(opts: {
  apiUrl: string;
  extraImgHosts?: string[];
  extraConnectHosts?: string[];
}): HostingPlugin[] {
  const api = new URL(opts.apiUrl).origin;
  const img = ["'self'", 'data:', 'blob:', api, 'https://*.supabase.co', ...(opts.extraImgHosts ?? [])].join(
    ' ',
  );
  const csp = [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self'",
    `img-src ${img}`,
    `connect-src ${["'self'", api, ...(opts.extraConnectHosts ?? [])].join(' ')}`,
    "font-src 'self'",
    "manifest-src 'self'",
    "worker-src 'self'",
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "object-src 'none'",
  ].join('; ');
  const htaccess = `# Generated by the build — do not edit by hand.
Options -Indexes
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{HTTPS} !=on
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
  # Single-page app: unknown paths serve index.html
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule ^ index.html [L]
</IfModule>
<IfModule mod_headers.c>
  Header always set Content-Security-Policy "${csp}"
  Header always set Strict-Transport-Security "max-age=63072000; includeSubDomains"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "DENY"
  Header always set Permissions-Policy "geolocation=(self), camera=(self), microphone=(), payment=()"
  Header always set Cross-Origin-Opener-Policy "same-origin"
  <FilesMatch "\\.(js|css|png|jpg|svg|webp|woff2)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "(index\\.html|sw\\.js|manifest\\.webmanifest)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
`;
  const headers: Record<string, string> = {
    'Content-Security-Policy': csp,
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'X-Frame-Options': 'DENY',
    'Permissions-Policy': 'geolocation=(self), camera=(self), microphone=(), payment=()',
    'Cross-Origin-Opener-Policy': 'same-origin',
  };
  return [
    {
      name: 'rozbazaar-hosting-headers',
      apply: 'build',
      generateBundle() {
        this.emitFile({ type: 'asset', fileName: '.htaccess', source: htaccess });
      },
    },
    {
      name: 'rozbazaar-preview-headers',
      apply: (_config, env) => Boolean(env.isPreview),
      configurePreviewServer(server) {
        server.middlewares.use((_req, res, next) => {
          for (const [k, v] of Object.entries(headers)) res.setHeader(k, v);
          next();
        });
      },
    },
  ];
}
